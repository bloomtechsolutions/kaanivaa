#!/usr/bin/env python3
"""Generate supabase/seed.sql from the Kaanivaa duty roster workbook.

Usage:  python3 scripts/xlsx_to_seed.py data/Kaanivaa_44_Duty_Roster_11-14_Nov_2026.xlsx > supabase/seed.sql
Requires: pip install openpyxl
"""
import sys
from datetime import datetime

import openpyxl

YEAR_MONTH = "2026-11"


def q(v):
    if v is None or str(v).strip() == "":
        return "null"
    return "'" + str(v).strip().replace("'", "''") + "'"


def to_date(label):  # '11 Nov 2026' -> '2026-11-11'
    return datetime.strptime(label.strip(), "%d %b %Y").strftime("%Y-%m-%d")


def main(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    out = ["-- Generated by scripts/xlsx_to_seed.py — safe to re-run (truncates roster data).",
           "begin;",
           "truncate public.draws, public.assignments, public.shifts, public.staff restart identity cascade;", ""]

    # Staff ---------------------------------------------------------------
    sa = wb["Staff Availability"]
    header_row = next(i for i, r in enumerate(sa.iter_rows(values_only=True), 1) if r[0] == "Name")
    staff_rows = []
    for r in sa.iter_rows(min_row=header_row + 1, values_only=True):
        if not r[0]:
            continue
        name, uid, email, status = r[0], r[1], r[2], r[3] or ""
        days = [d for d, flag in zip(("11", "12", "13", "14"), r[5:9]) if str(flag).strip().lower() == "yes"]
        dates = "array[" + ",".join(f"'{YEAR_MONTH}-{d}'" for d in days) + "]::date[]" if days else "'{}'::date[]"
        staff_rows.append(
            f"({q(name)}, {q(uid)}, {q(email.lower() if email else None)}, "
            f"{'true' if 'leader' in status.lower() else 'false'}, {q(status)}, {dates})")
    out.append("insert into public.staff (full_name, uid, email, is_leader, registration_status, available_dates) values")
    out.append(",\n".join(staff_rows) + ";\n")

    # Shifts + assignments --------------------------------------------------
    mr = wb["Master Roster"]
    header_row = next(i for i, r in enumerate(mr.iter_rows(values_only=True), 1) if r[0] == "Date")
    shifts, assigns = {}, []
    for r in mr.iter_rows(min_row=header_row + 1, values_only=True):
        if not r[0]:
            continue
        d = to_date(r[0])
        no = int(str(r[2]).split()[-1])
        start, end = [t.strip() for t in str(r[3]).split("-")]
        end = "24:00" if end == "00:00" else end
        shifts[(d, no)] = (start, end)
        assigns.append(f"('{d}', {no}, {q(r[5])}, {q(r[4])}, {q(r[8])})")

    out.append("insert into public.shifts (shift_date, shift_no, starts_at, ends_at) values")
    out.append(",\n".join(f"('{d}', {n}, '{s}', '{e}')" for (d, n), (s, e) in sorted(shifts.items())) + ";\n")

    out.append("insert into public.assignments (shift_id, staff_id, location, responsibility)")
    out.append("select s.id, st.id, v.location, v.responsibility from (values")
    out.append(",\n".join(assigns))
    out.append(") as v(shift_date, shift_no, full_name, location, responsibility)")
    out.append("join public.shifts s on s.shift_date = v.shift_date::date and s.shift_no = v.shift_no")
    out.append("join public.staff st on st.full_name = v.full_name;\n")
    out.append("commit;")
    print("\n".join(out))
    print(f"-- {len(staff_rows)} staff, {len(shifts)} shifts, {len(assigns)} assignments", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1])
